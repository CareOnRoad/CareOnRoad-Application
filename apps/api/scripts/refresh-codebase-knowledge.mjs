/* global console, process */

import { mkdir, readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const apiRoot = process.cwd();
const root = path.resolve(apiRoot, "..", "..");
const generatedDir = path.join(root, "docs", "obsidian", "generated");
const agentKnowledgeDir = path.join(root, ".agents", "knowledge");

const ignoredDirs = new Set([
  ".git",
  ".next",
  ".obsidian",
  ".tmp",
  "coverage",
  "dist",
  "models",
  "node_modules"
]);

const keyDocs = [
  "README.md",
  "AGENTS.md",
  "CAREONROAD_CODEBASE_HANDBOOK.md",
  "docs/SESSION_HANDOFF_BATCH_1_TO_6.md"
];

function repoPath(...parts) {
  return path.join(root, ...parts);
}

function normalize(filePath) {
  return path.relative(root, filePath).replaceAll(path.sep, "/");
}

async function exists(filePath) {
  try {
    await stat(filePath);
    return true;
  } catch {
    return false;
  }
}

async function listFiles(startDir, predicate = () => true) {
  if (!(await exists(startDir))) {
    return [];
  }

  const output = [];
  async function walk(dir) {
    const entries = await readdir(dir, { withFileTypes: true });
    for (const entry of entries) {
      if (ignoredDirs.has(entry.name)) {
        continue;
      }
      const fullPath = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        await walk(fullPath);
        continue;
      }
      if (entry.isFile() && predicate(fullPath)) {
        output.push(normalize(fullPath));
      }
    }
  }

  await walk(startDir);
  return output.sort((a, b) => a.localeCompare(b));
}

async function firstHeading(relativePath) {
  const fullPath = repoPath(...relativePath.split("/"));
  try {
    const content = await readFile(fullPath, "utf8");
    const heading = content.match(/^#\s+(.+)$/m);
    return heading?.[1]?.trim() ?? path.basename(relativePath);
  } catch {
    return path.basename(relativePath);
  }
}

function bulletLinks(files, fromGenerated = true) {
  const prefix = fromGenerated ? "../../../" : "../../";
  if (files.length === 0) {
    return "- None found";
  }
  return files.map((file) => `- [${file}](${prefix}${file})`).join("\n");
}

async function buildInventory() {
  const specFiles = await listFiles(repoPath("specs"), (file) => file.endsWith(".md") || file.endsWith(".yaml"));
  const migrationFiles = await listFiles(repoPath("supabase", "migrations"), (file) => file.endsWith(".sql"));
  const apiRoutes = await listFiles(repoPath("apps", "api", "app", "api"), (file) => file.endsWith("route.ts"));
  const repositoryContracts = await listFiles(repoPath("apps", "api", "src", "server", "repositories", "contracts"), (file) =>
    file.endsWith(".ts")
  );
  const featureTests = await listFiles(repoPath("apps", "api", "src"), (file) => /\.test\.tsx?$|\.integration\.test\.tsx?$|\.smoke\.test\.tsx?$/.test(file));
  const packageJson = JSON.parse(await readFile(path.join(apiRoot, "package.json"), "utf8"));

  const existingKeyDocs = [];
  for (const file of keyDocs) {
    if (await exists(repoPath(...file.split("/")))) {
      existingKeyDocs.push({
        file,
        title: await firstHeading(file)
      });
    }
  }

  return {
    generatedAt: new Date().toISOString(),
    keyDocs: existingKeyDocs,
    specFiles,
    migrationFiles,
    apiRoutes,
    repositoryContracts,
    featureTests,
    scripts: packageJson.scripts ?? {}
  };
}

function buildObsidianIndex(inventory) {
  const scriptLines = Object.entries(inventory.scripts)
    .map(([name, command]) => `- \`pnpm.cmd --filter @careonroad/api ${name}\`: \`${command}\``)
    .join("\n");

  return `# Codebase Knowledge Index

Generated by \`pnpm.cmd --filter @careonroad/api knowledge:refresh\` at ${inventory.generatedAt}.

Use this generated note as a fast map, then open the linked source files for the authoritative details. Do not store secrets in this vault.

## Core Links

- [[Vault Home]]
- [[Codebase Handbook]]
- [[Mechanic Operations]]
- [[Payment]]
- [[Patch 6 Payment Deferred]]
- [[Assignment State Machine]]
- [[Glossary]]
- [[Debug Journal]]

## Source Documents

${inventory.keyDocs.map((doc) => `- [${doc.title}](../../../${doc.file})`).join("\n")}

## Specs

${bulletLinks(inventory.specFiles)}

## Migrations

${bulletLinks(inventory.migrationFiles)}

## API Routes

${bulletLinks(inventory.apiRoutes)}

## Repository Contracts

${bulletLinks(inventory.repositoryContracts)}

## Test Files

${bulletLinks(inventory.featureTests)}

## Package Commands

${scriptLines || "- None found"}
`;
}

function buildAgentKnowledge(inventory) {
  return `# CareOnRoad Agent Knowledge Snapshot

Generated by \`pnpm.cmd --filter @careonroad/api knowledge:refresh\` at ${inventory.generatedAt}.

Read \`AGENTS.md\` first. This file is a generated local navigation snapshot for coding agents and must not contain credentials, raw env values, audio, provider responses, or production data.

## High-Signal Notes

- Root Obsidian vault: CareOnRoad monorepo root.
- Human-readable vault notes: \`docs/obsidian/\`.
- Obsidian generated index: \`docs/obsidian/generated/Codebase Knowledge Index.md\`.
- Payment is backend-only through payOS/VietQR; quote approval stops at
  \`awaiting_payment\`, and verified payment success is required before work starts.
- Mechanic ETA/media/checklist endpoints store metadata only and do not bypass assignment state transitions.
- Raw media and full sensitive text must not enter audit/outbox payloads.

## Authoritative Source Documents

${inventory.keyDocs.map((doc) => `- ${doc.file} (${doc.title})`).join("\n")}

## Specs

${inventory.specFiles.map((file) => `- ${file}`).join("\n") || "- None found"}

## Migrations

${inventory.migrationFiles.map((file) => `- ${file}`).join("\n") || "- None found"}

## API Routes

${inventory.apiRoutes.map((file) => `- ${file}`).join("\n") || "- None found"}

## Repository Contracts

${inventory.repositoryContracts.map((file) => `- ${file}`).join("\n") || "- None found"}

## Test Surface

${inventory.featureTests.map((file) => `- ${file}`).join("\n") || "- None found"}
`;
}

const inventory = await buildInventory();
await mkdir(generatedDir, { recursive: true });
await mkdir(agentKnowledgeDir, { recursive: true });
await writeFile(path.join(generatedDir, "Codebase Knowledge Index.md"), buildObsidianIndex(inventory), "utf8");
await writeFile(path.join(agentKnowledgeDir, "CODEBASE_KNOWLEDGE.md"), buildAgentKnowledge(inventory), "utf8");

console.log("Refreshed docs/obsidian/generated/Codebase Knowledge Index.md");
console.log("Refreshed .agents/knowledge/CODEBASE_KNOWLEDGE.md");
